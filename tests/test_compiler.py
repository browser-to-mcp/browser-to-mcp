from __future__ import annotations

from pathlib import Path

import pytest
from pydantic import ValidationError

from browser_to_mcp.compiler import (
    SchemaCompilationError,
    compile_workflow,
    compile_workflows,
)
from browser_to_mcp.loader import LoadedWorkflow, load_workflow
from browser_to_mcp.models import WorkflowInput

WORKFLOW_PATH = Path(__file__).parents[1] / "workflows" / "hn_search.yaml"


def test_compilation_is_deterministic_and_includes_provenance_schema() -> None:
    loaded = load_workflow(WORKFLOW_PATH)

    first = compile_workflow(loaded)
    second = compile_workflow(loaded)

    assert first.name == second.name == "hn_search"
    assert first.description == second.description
    assert first.input_schema == second.input_schema
    assert first.output_schema == second.output_schema
    assert first.output_schema["properties"]["workflow"] == {
        "const": "hn_search",
        "title": "Workflow",
        "type": "string",
    }
    assert first.output_schema["properties"]["manifest_digest"]["const"] == loaded.manifest_digest
    assert first.output_schema["properties"]["trace_path"] == {
        "anyOf": [{"type": "string"}, {"type": "null"}],
        "title": "Trace Path",
    }
    assert first.output_schema["properties"]["outputs"]["$ref"]
    assert "Read-only reviewed workflow" in first.description


def test_compiled_input_model_is_strict_and_preserves_constraints() -> None:
    compiled = compile_workflow(load_workflow(WORKFLOW_PATH))

    assert compiled.input_schema == {
        "additionalProperties": False,
        "properties": {
            "query": {
                "description": "Search query.",
                "minLength": 1,
                "title": "Query",
                "type": "string",
            }
        },
        "required": ["query"],
        "title": "HnSearchArguments",
        "type": "object",
    }
    assert compiled.input_model.model_validate({"query": "mcp"}).query == "mcp"

    for arguments in ({}, {"query": ""}, {"query": 42}, {"query": "mcp", "extra": True}):
        with pytest.raises(ValidationError):
            compiled.input_model.model_validate(arguments)


def test_compiled_output_model_maps_declared_fields_and_provenance() -> None:
    loaded = load_workflow(WORKFLOW_PATH)
    compiled = compile_workflow(loaded)
    result = {
        "workflow": "hn_search",
        "manifest_digest": loaded.manifest_digest,
        "outputs": {"results": "visible results"},
        "trace_path": None,
        "duration_seconds": 0.125,
    }

    assert compiled.output_model.model_validate(result).model_dump(mode="json") == result
    assert compiled.output_schema["properties"]["outputs"]["$ref"].endswith("Outputs")
    outputs_schema = compiled.output_schema["$defs"]["HnSearchOutputs"]
    assert outputs_schema["additionalProperties"] is False
    assert outputs_schema["properties"]["results"] == {
        "description": "Visible matching results.",
        "title": "Results",
        "type": "string",
    }
    assert outputs_schema["required"] == ["results"]


def test_compiler_rejects_generated_name_collisions() -> None:
    loaded = load_workflow(WORKFLOW_PATH)

    with pytest.raises(SchemaCompilationError, match="generated by workflows"):
        compile_workflows([loaded, loaded])


@pytest.mark.parametrize("name", ["Invalid-name", "1invalid", "invalid name", "class"])
def test_compiler_rejects_names_unsupported_by_mcp_models(name: str) -> None:
    source = load_workflow(WORKFLOW_PATH)
    invalid = source.workflow.model_copy(update={"name": name})

    with pytest.raises(SchemaCompilationError, match="Tool names"):
        compile_workflow(LoadedWorkflow(invalid, source.manifest_digest))


def test_compiler_rejects_unsupported_input_schema_types() -> None:
    source = load_workflow(WORKFLOW_PATH)
    invalid_input = WorkflowInput.model_construct(type="array", required=True)
    invalid = source.workflow.model_copy(update={"inputs": {"query": invalid_input}})

    with pytest.raises(SchemaCompilationError, match="not supported"):
        compile_workflow(LoadedWorkflow(invalid, source.manifest_digest))


def test_compiler_rejects_input_names_unsupported_by_python_argument_models() -> None:
    source = load_workflow(WORKFLOW_PATH)
    invalid = source.workflow.model_copy(
        update={"inputs": {"not-valid": source.workflow.inputs["query"]}}
    )

    with pytest.raises(SchemaCompilationError, match="Field names"):
        compile_workflow(LoadedWorkflow(invalid, source.manifest_digest))
