"""Compile validated workflows into deterministic MCP tool contracts."""

from __future__ import annotations

import keyword
import re
from collections.abc import Iterable
from dataclasses import dataclass
from typing import Annotated, Any, Literal

from mcp.server.fastmcp.utilities.func_metadata import ArgModelBase
from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    StrictBool,
    StrictFloat,
    StrictInt,
    StrictStr,
    create_model,
)

from browser_to_mcp.loader import LoadedWorkflow
from browser_to_mcp.models import (
    MAX_CELL_CHARS,
    RecordField,
    StructuredOutput,
    Workflow,
    WorkflowInput,
    WorkflowOutput,
    schema_field_name_error,
)

_TYPE_MAP: dict[str, type[Any]] = {
    "string": StrictStr,
    "integer": StrictInt,
    "number": StrictFloat,
    "boolean": StrictBool,
}
_TOOL_NAME_PATTERN = re.compile(r"^[a-z][a-z0-9_]*$")


class StrictArguments(ArgModelBase):
    """Reject undeclared workflow inputs at the MCP boundary."""

    model_config = ConfigDict(arbitrary_types_allowed=True, extra="forbid")


class StrictSchemaModel(BaseModel):
    """Keep generated result objects closed to undeclared fields."""

    model_config = ConfigDict(extra="forbid")


@dataclass(slots=True)
class SchemaCompilationError(Exception):
    """A workflow cannot be represented by the supported MCP schema subset."""

    path: str
    message: str

    def __str__(self) -> str:
        return f"{self.path}: {self.message}"


@dataclass(frozen=True, slots=True)
class CompiledWorkflow:
    """Deterministic MCP-facing contract for one loaded workflow."""

    loaded: LoadedWorkflow
    name: str
    description: str
    input_model: type[StrictArguments]
    input_schema: dict[str, Any]
    output_model: type[BaseModel]
    output_schema: dict[str, Any]


def compile_workflow(loaded: LoadedWorkflow) -> CompiledWorkflow:
    """Compile one validated workflow into input and output MCP schemas."""

    workflow = loaded.workflow
    name = _tool_name(workflow)
    input_model = _input_model(workflow)
    output_model = _output_model(loaded)
    return CompiledWorkflow(
        loaded=loaded,
        name=name,
        description=_tool_description(workflow),
        input_model=input_model,
        input_schema=input_model.model_json_schema(by_alias=True),
        output_model=output_model,
        output_schema=output_model.model_json_schema(by_alias=True),
    )


def compile_workflows(workflows: Iterable[LoadedWorkflow]) -> tuple[CompiledWorkflow, ...]:
    """Compile workflows and reject collisions before any tool is registered."""

    compiled: list[CompiledWorkflow] = []
    names: dict[str, int] = {}
    for index, loaded in enumerate(workflows):
        item = compile_workflow(loaded)
        previous = names.get(item.name)
        if previous is not None:
            raise SchemaCompilationError(
                "name",
                f"Tool name '{item.name}' is generated by workflows at indexes "
                f"{previous} and {index}.",
            )
        names[item.name] = index
        compiled.append(item)
    return tuple(compiled)


def _tool_name(workflow: Workflow) -> str:
    if not _TOOL_NAME_PATTERN.fullmatch(workflow.name) or keyword.iskeyword(workflow.name):
        raise SchemaCompilationError(
            "name",
            "Tool names must start with a lowercase letter and contain only lowercase "
            "letters, digits, and underscores.",
        )
    return workflow.name


def _input_model(workflow: Workflow) -> type[StrictArguments]:
    fields: dict[str, tuple[Any, Any]] = {}
    limits = {
        s.paging.max_pages_input: s.paging.max_pages
        for s in workflow.steps
        if s.paging and s.paging.max_pages_input
    }
    for name, definition in workflow.inputs.items():
        _validate_field_name(name, f"inputs.{name}")
        annotation = _type_for(definition.type, f"inputs.{name}.type")
        default: Any = ...
        if name in limits:
            annotation = Annotated[annotation, Field(ge=1, le=limits[name])]
            default = limits[name]
        elif not definition.required:
            annotation = annotation | None
            default = None
        fields[name] = (annotation, _field(default, definition))

    model_name = f"{_class_name(workflow.name)}Arguments"
    return create_model(model_name, __base__=StrictArguments, **fields)


def _output_model(loaded: LoadedWorkflow) -> type[BaseModel]:
    workflow = loaded.workflow
    output_fields: dict[str, tuple[Any, Any]] = {}
    for name, definition in workflow.outputs.items():
        _validate_field_name(name, f"outputs.{name}", model=StrictSchemaModel)
        annotation = _output_type(definition, f"outputs.{name}", _class_name(workflow.name) + name)
        output_fields[name] = (annotation, _field(..., definition))

    outputs_model = create_model(
        f"{_class_name(workflow.name)}Outputs",
        __base__=StrictSchemaModel,
        **output_fields,
    )
    return create_model(
        f"{_class_name(workflow.name)}Result",
        __base__=StrictSchemaModel,
        workflow=(Literal[workflow.name], ...),
        manifest_digest=(Literal[loaded.manifest_digest], ...),
        outputs=(outputs_model, ...),
        trace_path=(StrictStr | None, ...),
        duration_seconds=(StrictFloat, Field(..., ge=0)),
    )


def _output_type(definition, path, name):
    if not isinstance(definition, StructuredOutput):
        if definition.type == "number":
            return Annotated[StrictFloat, Field(allow_inf_nan=False)]
        return _type_for(definition.type, path + ".type")
    fields = {}
    for field, schema in definition.record_fields.items():
        _validate_field_name(field, f"{path}.{field}", model=StrictSchemaModel)
        annotation = _type_for(schema.type, f"{path}.{field}.type")
        if schema.type == "number":
            annotation = Annotated[StrictFloat, Field(allow_inf_nan=False)]
        elif schema.type == "string":
            annotation = Annotated[
                StrictStr, Field(min_length=1, max_length=MAX_CELL_CHARS, pattern=r"\S")
            ]
        if schema.nullable:
            annotation = annotation | None
        fields[field] = (annotation, _field(..., schema))
    record = create_model(name + "Record", __base__=StrictSchemaModel, **fields)
    if definition.type == "object":
        return record
    return Annotated[
        list[record],
        Field(min_length=0 if definition.allow_empty else 1, max_length=definition.max_items),
    ]


def _type_for(type_name: str, path: str) -> type[Any]:
    try:
        return _TYPE_MAP[type_name]
    except KeyError as error:
        raise SchemaCompilationError(
            path,
            f"Type '{type_name}' is not supported by the MCP schema compiler.",
        ) from error


def _field(
    default: Any, definition: WorkflowInput | WorkflowOutput | StructuredOutput | RecordField
) -> Any:
    kwargs: dict[str, Any] = {}
    if definition.description is not None:
        kwargs["description"] = definition.description
    if isinstance(definition, WorkflowInput) and definition.min_length is not None:
        kwargs["min_length"] = definition.min_length
    return Field(default=default, **kwargs)


def _validate_field_name(name: str, path: str, *, model: type[BaseModel] = StrictArguments) -> None:
    error = schema_field_name_error(name, model)
    if error:
        raise SchemaCompilationError(path, error)


def _class_name(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def _tool_description(workflow: Workflow) -> str:
    boundary = (
        "Read-only reviewed workflow; no forms are submitted, messages are sent, "
        "files are uploaded, money is spent, or authentication is used."
    )
    if workflow.permissions.downloads:
        boundary += " Declared downloads are permitted."
    return f"{workflow.description} {boundary}"
